-- ---------- İçe aktarmadan sonra ürün numarası sayacını düzelt ----------
create or replace function public.sync_products_id_seq()
returns void
language plpgsql security definer
set search_path = public
as $$
begin
    if not public.is_admin() then
        raise exception 'not allowed';
    end if;
    perform setval(pg_get_serial_sequence('public.products', 'id'), (select coalesce(max(id), 1) from public.products));
end;
$$;
revoke all on function public.sync_products_id_seq() from public, anon;
grant execute on function public.sync_products_id_seq() to authenticated;
